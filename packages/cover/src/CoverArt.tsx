/**
 * `<CoverArt edition={…}/>` — the inline, any-size render of the weekly
 * cover (T3). Same seed, same authored SVG as the build-time raster
 * (`render.ts`): the React surface and the committed assets can never
 * diverge. No client JS needed — it renders a static `<svg>` tree wherever
 * the file asset isn't wanted.
 */
import { authorCoverSvg, type CoverCanvas } from "./compose";
import { coverParams } from "./params";
import { loadCoverPalettes, type CoverPalette } from "./palettes";

export const COVER_ASPECTS = {
  "4:5": { width: 1600, height: 2000 },
  "16:9": { width: 1920, height: 1080 },
} as const;

export type CoverAspect = keyof typeof COVER_ASPECTS;

export function CoverArt({
  edition,
  aspect = "4:5",
  palettes,
  className,
}: {
  edition: Record<string, unknown>;
  /** 4:5 front-page crop (§2.2) or 16:9 landscape. */
  aspect?: CoverAspect;
  /** Curated palettes; defaults to config/cover-palettes.json. */
  palettes?: CoverPalette[];
  className?: string;
}) {
  const params = coverParams(edition, palettes ?? loadCoverPalettes());
  const canvas: CoverCanvas = COVER_ASPECTS[aspect];
  const svg = authorCoverSvg(params, canvas);
  return (
    <figure
      className={className}
      style={{ margin: 0, aspectRatio: aspect.replace(":", " / ") }}
      // Authored markup only — generated by authorCoverSvg from our own
      // palette config; no edition or user text ever lands inside it.
      dangerouslySetInnerHTML={{ __html: svg }}
      data-cover-composition={params.composition}
      data-cover-palette={params.palette.name}
      data-cover-seed={params.seed.slice(0, 12)}
    />
  );
}
